using System;

int numero1 = 10;
int numero2 = 5;

bool maiorQue = numero1 > numero2; 
bool menorQueOuIgual = numero1 <= numero2; 
bool diferente = numero1 != numero2; 

Console.WriteLine("Número 1 é maior que Número 2: " + maiorQue);
Console.WriteLine("Número 1 é menor ou igual a Número 2: " + menorQueOuIgual);
Console.WriteLine("Número 1 é diferente de Número 2: " + diferente);